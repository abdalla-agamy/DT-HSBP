function report = FullStochasticMetricsTest(swarmSize, randomSeed)
%FULLSTOCHASTICMETRICSTEST Verify full stochastic experiment metric exposure.
%
% Runs both HSBP and DTHSBP through the normal stochastic experiment path
% and validates that the returned result contains the core event, DT, rekey,
% communication, and computation metrics. This is a smoke test for the
% experiment reporting layer, not a comparative performance study.

    if nargin < 1
        swarmSize = 1000;
    end
    if nargin < 2
        randomSeed = 42;
    end

    hsbp = runStochasticExperiment("HSBP", swarmSize, 1, randomSeed);
    dt = runStochasticExperiment("DTHSBP", swarmSize, 1, randomSeed);

    requiredFields = { ...
        'joinEvents', ...
        'leaveEvents', ...
        'failureEvents', ...
        'dtDisturbanceCount', ...
        'dtPredictionsCreated', ...
        'dtPredictionsRealized', ...
        'dtPredictionsUnrealized', ...
        'dtRealizationRatio', ...
        'predictedLeaves', ...
        'localRekeys', ...
        'batchRekeys', ...
        'totalMessages', ...
        'totalBytes', ...
        'communicationCost', ...
        'totalEncryptions', ...
        'totalKeysGenerated', ...
        'totalDecryptions', ...
        'totalHashOperations', ...
        'totalRandomNumbers' ...
    };

    hsbpFieldsPresent = all(isfield(hsbp, requiredFields));
    dtFieldsPresent = all(isfield(dt, requiredFields));

    dtMetricInvariant = ...
        (dt.dtPredictionsUnrealized == ...
            max(0, dt.dtPredictionsCreated - dt.dtPredictionsRealized));

    if dt.dtPredictionsCreated > 0
        dtRatioInvariant = abs( ...
            dt.dtRealizationRatio - ...
            dt.dtPredictionsRealized / dt.dtPredictionsCreated) < 1e-12;
    else
        dtRatioInvariant = isnan(dt.dtRealizationRatio);
    end

    hsbpNoDTInvariant = ...
        (hsbp.dtPredictionsCreated == 0) && ...
        (hsbp.dtPredictionsRealized == 0) && ...
        (hsbp.dtPredictionsUnrealized == 0) && ...
        isnan(hsbp.dtRealizationRatio);

    resultSuccessInvariant = hsbp.success && dt.success;

    report = struct();
    report.swarmSize = swarmSize;
    report.randomSeed = randomSeed;
    report.hsbp = hsbp;
    report.dthsbp = dt;
    report.hsbpFieldsPresent = hsbpFieldsPresent;
    report.dthsbpFieldsPresent = dtFieldsPresent;
    report.dtMetricInvariant = dtMetricInvariant;
    report.dtRatioInvariant = dtRatioInvariant;
    report.hsbpNoDTInvariant = hsbpNoDTInvariant;
    report.resultSuccessInvariant = resultSuccessInvariant;

    fprintf('============================================\n');
    fprintf('Full Stochastic Metrics Test\n');
    fprintf('============================================\n');
    fprintf('Swarm size                  : %d\n', swarmSize);
    fprintf('Random seed                 : %d\n', randomSeed);
    fprintf('\n');
    fprintf('HSBP join/leave/failure     : [%d %d %d]\n', ...
        hsbp.joinEvents, hsbp.leaveEvents, hsbp.failureEvents);
    fprintf('HSBP local/batch rekeys     : [%d %d]\n', ...
        hsbp.localRekeys, hsbp.batchRekeys);
    fprintf('HSBP DT predictions         : [%d %d %d]\n', ...
        hsbp.dtPredictionsCreated, ...
        hsbp.dtPredictionsRealized, ...
        hsbp.dtPredictionsUnrealized);
    fprintf('HSBP DT realization ratio   : %g\n', hsbp.dtRealizationRatio);
    fprintf('HSBP messages/bytes         : [%d %d]\n', ...
        hsbp.totalMessages, hsbp.totalBytes);
    fprintf('\n');
    fprintf('DTHSBP join/leave/failure   : [%d %d %d]\n', ...
        dt.joinEvents, dt.leaveEvents, dt.failureEvents);
    fprintf('DTHSBP local/batch rekeys   : [%d %d]\n', ...
        dt.localRekeys, dt.batchRekeys);
    fprintf('DTHSBP DT predictions       : [%d %d %d]\n', ...
        dt.dtPredictionsCreated, ...
        dt.dtPredictionsRealized, ...
        dt.dtPredictionsUnrealized);
    fprintf('DTHSBP DT realization ratio : %g\n', dt.dtRealizationRatio);
    fprintf('DTHSBP messages/bytes       : [%d %d]\n', ...
        dt.totalMessages, dt.totalBytes);
    fprintf('\n');
    fprintf('Required fields HSBP        : %d\n', hsbpFieldsPresent);
    fprintf('Required fields DTHSBP      : %d\n', dtFieldsPresent);
    fprintf('DT metric invariant          : %d\n', dtMetricInvariant);
    fprintf('DT ratio invariant           : %d\n', dtRatioInvariant);
    fprintf('HSBP no-DT invariant         : %d\n', hsbpNoDTInvariant);
    fprintf('Success invariant             : %d\n', resultSuccessInvariant);
    fprintf('\n');

    if ~(hsbpFieldsPresent && ...
            dtFieldsPresent && ...
            dtMetricInvariant && ...
            dtRatioInvariant && ...
            hsbpNoDTInvariant && ...
            resultSuccessInvariant)
        error('FullStochasticMetricsTest:Failed', ...
            'Full stochastic metrics validation failed.');
    end

    fprintf('Full stochastic metrics validation: PASS\n');
    fprintf('============================================\n');
end
