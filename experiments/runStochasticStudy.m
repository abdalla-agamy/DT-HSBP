function results = runStochasticStudy(protocols, swarmSizes, repetitions, baseSeed)
%RUNSTOCHASTICSTUDY Execute repeated Poisson-driven stochastic studies.
%
% RESULTS = RUNSTOCHASTICSTUDY(PROTOCOLS,SWARMSIZES,REPETITIONS,BASESEED)
% runs the existing stochastic simulation independently for every
% protocol/swarm-size/repetition combination.
%
% The stochastic workload uses config.m rates and simulation settings.
% Warm-up is intentionally not performed here: every observation is a
% complete independent stochastic simulation and its seed is explicit.

    if nargin < 1 || isempty(protocols)
        protocols = ["FlatSBP","HSBP","DTHSBP"];
    end
    if nargin < 2 || isempty(swarmSizes)
        swarmSizes = [1000 2000 3000 4000 5000];
    end
    if nargin < 3 || isempty(repetitions)
        repetitions = 10;
    end
    if nargin < 4 || isempty(baseSeed)
        baseSeed = 42;
    end

    protocols = string(protocols(:));
    swarmSizes = swarmSizes(:).';

    if isempty(protocols)
        error('runStochasticStudy:EmptyProtocols', 'At least one protocol is required.');
    end
    if any(~ismember(protocols, ["FlatSBP","HSBP","DTHSBP"]))
        error('runStochasticStudy:UnknownProtocol', ...
            'Protocols must be FlatSBP, HSBP, or DTHSBP.');
    end
    if isempty(swarmSizes) || any(~isfinite(swarmSizes)) || ...
            any(swarmSizes < 1) || any(mod(swarmSizes,1) ~= 0)
        error('runStochasticStudy:InvalidSwarmSizes', ...
            'swarmSizes must contain positive integers.');
    end
    if repetitions < 1 || mod(repetitions,1) ~= 0
        error('runStochasticStudy:InvalidRepetitions', ...
            'repetitions must be a positive integer.');
    end
    if baseSeed < 0 || mod(baseSeed,1) ~= 0
        error('runStochasticStudy:InvalidBaseSeed', ...
            'baseSeed must be a non-negative integer.');
    end

    totalRuns = numel(protocols) * numel(swarmSizes) * repetitions;
    results = repmat(emptyResult(), totalRuns, 1);

    index = 0;
    for p = 1:numel(protocols)
        for n = 1:numel(swarmSizes)
            for r = 1:repetitions
                index = index + 1;
                seed = baseSeed + r - 1;
                results(index) = runStochasticExperiment( ...
                    protocols(p), swarmSizes(n), r, seed);
            end
        end
    end
end

function result = emptyResult()
    result = struct( ...
        'protocol', "", ...
        'eventType', "Stochastic", ...
        'runID', 0, ...
        'randomSeed', 0, ...
        'initialSwarmSize', 0, ...
        'finalActiveUAVs', 0, ...
        'simulationTime', 0, ...
        'timeStep', 0, ...
        'joinRate', 0, ...
        'leaveRate', 0, ...
        'failureRate', 0, ...
        'joinEvents', 0, ...
        'leaveEvents', 0, ...
        'failureEvents', 0, ...
        'rejectedJoins', 0, ...
        'predictedLeaves', 0, ...
        'localRekeys', 0, ...
        'batchRekeys', 0, ...
        'totalMessages', 0, ...
        'totalBytes', 0, ...
        'communicationCost', 0, ...
        'totalEncryptions', 0, ...
        'totalKeysGenerated', 0, ...
        'totalDecryptions', 0, ...
        'totalHashOperations', 0, ...
        'totalRandomNumbers', 0, ...
        'success', false, ...
        'status', "NotExecuted");
end
