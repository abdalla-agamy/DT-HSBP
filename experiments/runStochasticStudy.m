function results = runStochasticStudy(protocols,swarmSizes,repetitions,baseSeed,varargin)
%RUNSTOCHASTICSTUDY Execute repeated Poisson-driven stochastic studies.

    p = inputParser;
    addParameter(p,'UseParallel',false,@(x)islogical(x) && isscalar(x));
    parse(p,varargin{:});
    useParallel = p.Results.UseParallel;

    if nargin < 1 || isempty(protocols), protocols = ["FlatSBP","HSBP","DTHSBP"]; end
    if nargin < 2 || isempty(swarmSizes), swarmSizes = [1000 2000 3000 4000 5000]; end
    if nargin < 3 || isempty(repetitions), repetitions = 10; end
    if nargin < 4 || isempty(baseSeed), baseSeed = 42; end

    protocols = string(protocols(:));
    swarmSizes = swarmSizes(:).';

    if isempty(protocols), error('runStochasticStudy:EmptyProtocols','At least one protocol is required.'); end
    if any(~ismember(protocols,["FlatSBP","HSBP","DTHSBP"]))
        error('runStochasticStudy:UnknownProtocol','Protocols must be FlatSBP, HSBP, or DTHSBP.');
    end
    if isempty(swarmSizes) || any(~isfinite(swarmSizes)) || any(swarmSizes < 1) || any(mod(swarmSizes,1) ~= 0)
        error('runStochasticStudy:InvalidSwarmSizes','swarmSizes must contain positive integers.');
    end
    if repetitions < 1 || mod(repetitions,1) ~= 0
        error('runStochasticStudy:InvalidRepetitions','repetitions must be a positive integer.');
    end
    if baseSeed < 0 || mod(baseSeed,1) ~= 0
        error('runStochasticStudy:InvalidBaseSeed','baseSeed must be a non-negative integer.');
    end
    if useParallel && ~license('test','Distrib_Computing_Toolbox')
        error('runStochasticStudy:ParallelToolboxRequired', ...
            ['UseParallel=true requires the Parallel Computing Toolbox. ' ...
             'Install/enable it or set UseParallel=false.']);
    end

    totalRuns = numel(protocols)*numel(swarmSizes)*repetitions;
    results = repmat(emptyResult(),totalRuns,1);

    runPlan = repmat(struct('protocol',"",'swarmSize',0,'runID',0,'seed',0),totalRuns,1);
    index = 0;
    for pIndex = 1:numel(protocols)
        for nIndex = 1:numel(swarmSizes)
            for r = 1:repetitions
                index = index + 1;
                runPlan(index).protocol = protocols(pIndex);
                runPlan(index).swarmSize = swarmSizes(nIndex);
                runPlan(index).runID = r;
                runPlan(index).seed = baseSeed + r - 1;
            end
        end
    end

    if useParallel
        parfor k = 1:totalRuns
            plan = runPlan(k);
            results(k) = runStochasticExperiment(plan.protocol,plan.swarmSize,plan.runID,plan.seed);
        end
    else
        for k = 1:totalRuns
            plan = runPlan(k);
            results(k) = runStochasticExperiment(plan.protocol,plan.swarmSize,plan.runID,plan.seed);
        end
    end
end

